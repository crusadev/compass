// Ranks source files by how much code they hold against how many compass files
// cite them, so the next domain to map is chosen by evidence rather than taste.
//
// Seeding domains from schema modules or folder names misses whole categories:
// a flow spanning six tables, a scheduler, a notification system, a legacy
// monolith. Size against citations sees all of them, because it does not care
// whether a domain owns a table.
//
//   node tools/context/scan-coverage.mjs [--json]

import { readdirSync, existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { ROOT, read, tracked, packageOf } from './lib/repo.mjs'
import { config } from './lib/config.mjs'

const COMPASS_DIR = config().contextDir
const OUT = `${config().generatedDir}/coverage.md`

// Below this a file is a detail of some domain, not a domain of its own.
const MIN_LINES = config().coverageMinLines

const EXCLUDED = new RegExp(
  config().exclude.concat(config().excludeFromUsage).map((d) => `^${d}`).join('|') ||
    '^$',
)

const compassFiles = existsSync(path.join(ROOT, COMPASS_DIR))
  ? readdirSync(path.join(ROOT, COMPASS_DIR))
      .filter((n) => n.endsWith('.md'))
      .map((n) => `${COMPASS_DIR}/${n}`)
  : []

const compassText = new Map(compassFiles.map((f) => [f, read(f)]))

const sources = tracked(config().source)
  .filter((f) => !EXCLUDED.test(f))
  .map((file) => ({ file, lines: read(file).split('\n').length }))
  .filter((f) => f.lines >= MIN_LINES)

// A file is cited if any compass file names it, by full path or by a basename
// distinctive enough to mean only this file.
//
// Counted across EVERY tracked source, not just the large ones ranked here. A
// compass file citing `config.ts` means the 98-line backend/api/config.ts, and
// counting only files over the line threshold made the 417-line tutorials
// config.ts look like the unique owner of that name.
const basenameCount = new Map()
for (const file of tracked(config().source)) {
  const base = path.basename(file)
  basenameCount.set(base, (basenameCount.get(base) ?? 0) + 1)
}

const citedBy = ({ file }) => {
  const base = path.basename(file)
  const distinctive = basenameCount.get(base) === 1
  const names = []
  for (const [compass, text] of compassText) {
    if (text.includes(file) || (distinctive && text.includes(base))) {
      names.push(path.basename(compass, '.md'))
    }
  }
  return names
}

const rows = sources
  .map((s) => {
    const cited = citedBy(s)
    return { ...s, package: packageOf(s.file), cited, citations: cited.length }
  })
  .sort((a, b) => b.lines - a.lines)

// Cited by three or more domains. Whether or not one of them owns the file, this
// is where change coupling concentrates: an edit here reaches every domain listed.
const shared = rows.filter((r) => r.citations >= 3)
// Large and named by nobody: either a blind spot or a dead zone. Both worth a look.
const invisible = rows.filter((r) => r.citations === 0)

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ rows, shared, invisible }, null, 2))
  process.exit(0)
}

const lines = []
const say = (line = '') => lines.push(line)

const table = (items, limit = 30) => {
  if (items.length === 0) return say('None.')
  say('| File | Lines | Package | Cited by |')
  say('| --- | --- | --- | --- |')
  for (const r of items.slice(0, limit)) {
    say(
      `| \`${r.file}\` | ${r.lines} | ${r.package} | ${
        r.cited.length ? r.cited.join(', ') : 'nobody'
      } |`
    )
  }
  if (items.length > limit) say(`| ... and ${items.length - limit} more | | | |`)
}

say('# Compass coverage')
say()
say('Generated by `node tools/context/scan-coverage.mjs`. Do not edit by hand.')
say()
say(
  `${rows.length} source files of ${MIN_LINES}+ lines, against ${compassFiles.length} compass files.`
)
say()

say('## Cross-cutting')
say()
say(
  'Three or more domains cite these. An edit here reaches every domain listed, ' +
  'whether or not one of them owns the file. A file cited by many domains and ' +
  'named after none of them is the clearest gap.'
)
say()
table(shared)
say()

say('## Large and cited by nobody')
say()
say('Either a domain nothing has mapped yet, or code nothing uses. Check which.')
say()
table(invisible)
say()

writeFileSync(path.join(ROOT, OUT), `${lines.join('\n')}\n`)
console.error(
  `${OUT}: ${rows.length} files over ${MIN_LINES} lines, ` +
    `${shared.length} cross-cutting, ${invisible.length} uncited`
)
